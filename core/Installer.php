<?php
declare(strict_types=1);

namespace MagicCMS\Core;

require_once __DIR__ . '/Database.php';
require_once __DIR__ . '/Migrator.php';

/** Logic behind setup.php. Works without a config file (it creates it). */
final class Installer
{
    public static function requirements(): array
    {
        $root = dirname(__DIR__);
        $w = fn(string $d) => is_dir("$root/$d") && is_writable("$root/$d");
        return [
            ['PHP ≥ 8.1', version_compare(PHP_VERSION, '8.1.0', '>='), PHP_VERSION, true],
            ['PDO MySQL', extension_loaded('pdo_mysql'), '', true],
            ['mbstring', extension_loaded('mbstring'), '', true],
            ['fileinfo', extension_loaded('fileinfo'), '', true],
            ['dom / libxml (HTML sanitizer)', extension_loaded('dom'), '', true],
            ['GD (avatar resizing)', extension_loaded('gd'), '', false],
            ['WebP support in GD', function_exists('imagewebp'), 'falls back to JPEG', false],
            ['Argon2id password hashing', defined('PASSWORD_ARGON2ID'), 'falls back to bcrypt', false],
            ['upload_max_filesize ≥ 5M (avatars)', self::bytes((string) ini_get('upload_max_filesize')) >= 5 * 1048576 && self::bytes((string) ini_get('post_max_size')) >= 5 * 1048576, 'now: ' . ini_get('upload_max_filesize') . ' / post ' . ini_get('post_max_size') . ' – raise in php.ini', false],
            ['config/ writable', $w('config'), '', true],
            ['uploads/ writable', $w('uploads'), '', true],
            ['cache/ writable', $w('cache'), '', false],
        ];
    }

    private static function bytes(string $v): int
    {
        $n = (int) $v;
        return match (strtolower(substr(trim($v), -1))) { 'g' => $n << 30, 'm' => $n << 20, 'k' => $n << 10, default => $n };
    }

    public static function requirementsOk(): bool
    {
        foreach (self::requirements() as [, $ok, , $hard]) {
            if ($hard && !$ok) {
                return false;
            }
        }
        return true;
    }

    /** @return string|null error */
    public static function testDb(array $c): ?string
    {
        if (!preg_match('/^[a-z][a-z0-9_]{0,15}$/', (string) $c['prefix'])) {
            return 'Table prefix must start with a letter and contain only a-z, 0-9, _ (max 16 chars).';
        }
        try {
            $db = new Database($c);
            if ($db->val('SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?', [$c['prefix'] . 'users']) && (int) $db->val('SELECT COUNT(*) FROM {users}') > 0) {
                return 'MagicCMS tables with users already exist for this prefix. Choose another prefix or an empty database.';
            }
        } catch (\Throwable $e) {
            return 'Could not connect: ' . $e->getMessage();
        }
        return null;
    }

    /** @return string|null error */
    public static function install(array $dbc, array $site, array $admin): ?string
    {
        $root = dirname(__DIR__);
        try {
            $db = new Database($dbc);

            // 1. Schema
            $sql = (string) file_get_contents($root . '/migrations/0001_init.sql');
            $sql = preg_replace('/^\s*--.*$/m', '', $sql);
            foreach (array_filter(array_map('trim', explode(";\n", $sql))) as $stmt) {
                $db->raw($stmt);
            }

            // 2. Seed (transactional)
            $db->transaction(function (Database $db) use ($site, $admin) {
                self::seed($db, $site, $admin);
            });
            Migrator::upgrade($db); // 0002+ (forum, …): same path as a later upgrade
        } catch (\Throwable $e) {
            return 'Installation failed: ' . $e->getMessage();
        }

        // 3. Config + lock file
        $config = [
            'db' => $dbc,
            'app' => [
                'url' => rtrim($site['url'], '/'),
                'debug' => false,
                'secret' => bin2hex(random_bytes(32)),
            ],
        ];
        $php = "<?php\n// Generated by MagicCMS setup on " . gmdate('c') . "\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents($root . '/config/config.php', $php, LOCK_EX) === false) {
            return 'Could not write config/config.php – check folder permissions.';
        }
        @chmod($root . '/config/config.php', 0640);
        file_put_contents($root . '/config/installed.lock', json_encode(['version' => '0.1.0', 'installed' => gmdate('c')]), LOCK_EX);
        return null;
    }

    private static function seed(Database $db, array $site, array $admin): void
    {
        $now = gmdate('Y-m-d H:i:s');

        // Roles
        $roles = [['guest', 'Guest', 0], ['member', 'Member', 10], ['moderator', 'Moderator', 50], ['admin', 'Administrator', 80], ['superadmin', 'Superadmin', 100]];
        $rid = [];
        foreach ($roles as [$slug, $name, $lvl]) {
            $rid[$slug] = $db->insert('INSERT INTO {roles} (slug, name, level, is_system) VALUES (?,?,?,1)', [$slug, $name, $lvl]);
        }

        // Permissions
        $perms = [
            'admin.access' => 'Open the admin area', 'admin.settings' => 'Edit site settings', 'admin.appearance' => 'Edit appearance',
            'admin.users' => 'Manage users', 'admin.panels' => 'Manage panels', 'admin.navigation' => 'Manage navigation',
            'admin.pages' => 'Manage pages', 'chat.read' => 'Read the chat', 'chat.post' => 'Post in the chat',
            'chat.moderate' => 'Delete chat messages',
        ];
        $pid = [];
        foreach ($perms as $k => $label) {
            $pid[$k] = $db->insert('INSERT INTO {permissions} (perm_key, label) VALUES (?,?)', [$k, $label]);
        }
        $grant = [
            'guest' => ['chat.read'],
            'member' => ['chat.read', 'chat.post'],
            'moderator' => ['chat.read', 'chat.post'],
            'admin' => array_keys($perms),
        ];
        foreach ($grant as $role => $keys) {
            foreach ($keys as $k) {
                $db->exec('INSERT INTO {role_permissions} (role_id, permission_id) VALUES (?,?)', [$rid[$role], $pid[$k]]);
            }
        }

        // First user = Superadmin
        $db->exec(
            'INSERT INTO {users} (username, email, password_hash, role_id, status, timezone, created_at, last_login) VALUES (?,?,?,?,?,?,?,?)',
            [$admin['username'], $admin['email'], password_hash($admin['password'], defined('PASSWORD_ARGON2ID') ? PASSWORD_ARGON2ID : PASSWORD_BCRYPT), $rid['superadmin'], 'active', $site['timezone'], $now, null]
        );

        // Settings
        $settings = [
            'site.name' => $site['name'], 'site.tagline' => 'Play bold. Win together.', 'site.description' => $site['name'] . ' – powered by MagicCMS',
            'site.lang' => 'en', 'site.timezone' => $site['timezone'], 'site.maintenance' => false,
            'site.footer' => '© {year} ' . $site['name'],
            'layout.mode' => 'right', 'theme.active' => $site['theme'],
            'auth.registration' => 'open',
            'upload.avatar_max_mb' => 5, 'online.window_min' => 5,
            'appearance.mode_default' => 'dark', 'appearance.allow_user_mode' => true, 'appearance.scheme' => 'crimson',
            'appearance.colors' => new \stdClass(), 'appearance.radius' => 16, 'appearance.motion' => 'full',
            'nav.button_style' => 'gradient', 'nav.hover_fx' => 'shine',
        ];
        if (!class_exists(Appearance::class)) {
            require_once MCMS_ROOT . '/core/Appearance.php';
        }
        $themeMeta = json_decode((string) @file_get_contents(MCMS_ROOT . '/themes/' . $site['theme'] . '/theme.json'), true) ?: [];
        $td = (array) ($themeMeta['defaults'] ?? []);
        if (isset($td['scheme']) && isset(Appearance::PRESETS[$td['scheme']])) {
            $settings['appearance.scheme'] = $td['scheme'];
        }
        if (isset($td['mode']) && in_array($td['mode'], ['dark', 'light', 'auto'], true)) {
            $settings['appearance.mode_default'] = $td['mode'];
        }
        if (isset($td['radius'])) {
            $settings['appearance.radius'] = max(0, min(32, (int) $td['radius']));
        }
        foreach ($settings as $k => $v) {
            $db->exec('INSERT INTO {settings} (`key`, `value`) VALUES (?,?)', [$k, json_encode($v, JSON_UNESCAPED_UNICODE)]);
        }

        // Modules
        foreach (['home', 'auth', 'profile', 'members', 'pages', 'chat', 'admin'] as $m) {
            $db->exec('INSERT INTO {modules} (module_key, enabled, is_core) VALUES (?,1,1)', [$m]);
        }

        // Panels
        $vis = fn(string $who = 'all', bool $mobile = true) => json_encode(['who' => $who, 'mobile' => $mobile]);
        $panels = [
            // One column on the right is the default layout. The login/register/account area lives in the header, so the
            // "Account" panel is installed switched OFF (enable it in Admin → Panels if your theme has no account area on top).
            ['chat', 'Shoutbox', 'right', 1, 1], ['site_stats', 'Site Stats', 'right', 2, 1], ['online_users', 'Online Users', 'right', 3, 1],
            ['user_box', 'Account', 'right', 9, 0],
        ];
        foreach ($panels as [$key, $title, $pos, $ord, $on]) {
            $db->exec('INSERT INTO {panels} (panel_key, title, position, sort_order, enabled, visibility) VALUES (?,?,?,?,?,?)', [$key, $title, $pos, $ord, $on, $vis()]);
        }

        // Navigation + demo page
        $db->exec('INSERT INTO {pages} (slug, title, content, published, created_at, updated_at) VALUES (?,?,?,?,?,?)', [
            'about', 'About us',
            '<p>Welcome to <strong>' . htmlspecialchars($site['name']) . '</strong>! This is a custom page – edit or delete it in <em>Admin → Pages</em>, and link to any page from <em>Admin → Navigation</em>.</p>',
            1, $now, $now,
        ]);
        $pageId = (int) $db->val('SELECT id FROM {pages} WHERE slug = ?', ['about']);
        $menu = $db->insert('INSERT INTO {menus} (menu_key, title) VALUES (?,?)', ['main', 'Main menu']);
        $db->insert('INSERT INTO {menus} (menu_key, title) VALUES (?,?)', ['footer', 'Footer menu']);
        $items = [['Home', '🏠', 'module', 'home'], ['Members', '👥', 'module', 'members'], ['About', 'ℹ️', 'page', (string) $pageId]];
        foreach ($items as $i => [$label, $icon, $type, $ref]) {
            $db->exec(
                'INSERT INTO {menu_items} (menu_id, label, icon, target_type, target_ref, visibility, sort_order) VALUES (?,?,?,?,?,?,?)',
                [$menu, $label, $icon, $type, $ref, $vis(), $i + 1]
            );
        }

        $db->exec("INSERT INTO {settings} (`key`, `value`) VALUES ('schema.version', '1')");
    }

    /** Try to remove the installer. @return bool true if setup.php is gone */
    public static function selfDelete(): bool
    {
        $f = dirname(__DIR__) . '/setup.php';
        return !is_file($f) || @unlink($f);
    }
}
